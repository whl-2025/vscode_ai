def bubblesort(lst): 
    n = len(lst)   #获取列表长度。这是我们的边界条件之一.
    
    for i in range (n-1,0,-1):      #从最后一个元素开始，到第一个位置结束（包括两个端点).我们减去i是因为在每次迭代中已经排除了最大的未处理数字的可能性。 这是因为一旦所有已知数都被放置正确地的话，下一次循环将对它们进行检查并将其移动到底部.
        for j in range(n-1, i+1):   #这个内部for loop从第一个元素开始到当前正在排序的位置（包括两个端点). 这是因为我们希望最大未处理数字被放置在正确的位置上。如果它已经是最大的，就不需要再检查了.
            if lst[j] > lst[j+1]:   #这个if语句用于交换元素的条件 -> (lst[i-2])应该放在(lst[0...n-(i)]. 这是因为我们希望最大未处理数字被放置在正确的位置上。
                temp = lst[j]       #创建一个临时变量来保存当前值，以便稍后进行交换操作.
                lst[j],lst[j+1]= lst[j+1],temp  #执行元素的交换（从第一个位置到第i个索引的位置和下一对数字之间的比较).这是通过将当前值赋给一个临时变量，然后将其与后面的数进行替换来完成.
    return(lst)   #返回排序后的列表。 这行代码是冒泡排序算法的核心部分 -> (我们不断地交换相邻元素的位置直到它们按正确的顺序（从最小到最大或反之亦然，对于整数来说就是升序/降序)为止).
   #示例用法:  print(bubblesort([5,2134678,-90, -1]))   => [-90, -1, 5, 2134678]。它会打印出排序后的列表.
